func TestSuppresses(t *testing.T) {
	tests := []struct {
		text string
		want bool
	}{
		{"//swallowcheck:ignore", true},
		{"// swallowcheck:ignore", true},
		{"//swallowcheck:ignore // the fallback value is correct here", true},
		{"//swallowcheck:ignore\t// tab before the reason", true},
		{"//nolint", true},
		{"//nolint // generated by hand", true},
		{"//nolint:swallowcheck", true},
		{"//nolint:gosec,swallowcheck", true},
		{"//nolint:swallowcheck // reason", true},
		{"//swallowcheck:ignored", false},
		{"//swallowcheck:ignoreall", false},
		{"//swallowcheck:ignore,other", false},
		{"//goroutinecheck:ignore", false},
		{"//nolint:gosec", false},
		{"//nolint:errcheck,bodyclose", false},
		{"//nolint:swallowcheckx", false},
		{"//nolint: swallowcheck", false},
		{"//nolintx", false},
		{"// see the nolint docs for details", false},
		{"// nothing to see here", false},
		{"// swallowcheckers are great", false},
		{"/* swallowcheck:ignore */", false},
		{"//customlint:swallowcheck", false},
		{"// nolint is not something we use here", false},
		{"//nolint because the vendor said so", false},
		{"//swallowcheck:ignore a fallback is fine", false},
		{"//nolint:swallowcheck   // reason after spaces", true},
	}
	for _, tt := range tests {
		t.Run(tt.text, func(t *testing.T) {
			if got := Suppresses(tt.text, "swallowcheck"); got != tt.want {
				t.Errorf("Suppresses(%q) = %v, want %v", tt.text, got, tt.want)
			}
		})
	}
}

const placement = `package p

func f() {
	//x:ignore
	_ = 1
	_ = 2 //x:ignore
	_ = 3
	// a reason on its own line
	//x:ignore // and one after it
	_ = 4
}
`

func TestSetPlacement(t *testing.T) {
	fset := token.NewFileSet()
	f, err := parser.ParseFile(fset, "p.go", placement, parser.ParseComments)
	if err != nil {
		t.Fatal(err)
	}
	read := func(string) ([]byte, error) { return []byte(placement), nil }
	s := Collect(fset, []*ast.File{f}, "x", read)
	line := func(n int) token.Pos { return fset.File(f.Pos()).LineStart(n) }
	tests := []struct {
		name  string
		line  int
		above bool
		on    bool
	}{
		{"statement under an own-line directive", 5, true, false},
		{"statement with a trailing directive", 6, false, true},
		{"statement under a line that ends in a directive", 7, false, false},
		{"directive line itself", 4, false, true},
		{"statement under a directive with a reason", 10, true, false},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			if got := s.OwnLineAbove(line(tt.line)); got != tt.above {
				t.Errorf("OwnLineAbove(line %d) = %v, want %v", tt.line, got, tt.above)
			}
			if got := s.OnLine(line(tt.line)); got != tt.on {
				t.Errorf("OnLine(line %d) = %v, want %v", tt.line, got, tt.on)
			}
		})
	}
}

func TestSetUnreadableFile(t *testing.T) {
	fset := token.NewFileSet()
	f, err := parser.ParseFile(fset, "p.go", placement, parser.ParseComments)
	if err != nil {
		t.Fatal(err)
	}
	s := Collect(fset, []*ast.File{f}, "x", func(string) ([]byte, error) { return nil, errors.New("unreadable") })
	pos := fset.File(f.Pos()).LineStart(5)
	if s.OwnLineAbove(pos) {
		t.Error("OwnLineAbove = true for a file whose source could not be read, want false")
	}
	if !s.OnLine(fset.File(f.Pos()).LineStart(4)) {
		t.Error("OnLine = false on the directive's own line, want true")
	}
}
